/* =========================================================================
 * 5. VISTA DE ÓRDENES ABIERTAS (informe 5 y disponibilidad de ofertas)
 * ========================================================================= */

CREATE OR REPLACE VIEW vw_OrdenesAbiertas AS
SELECT o.id_orden,
       o.descripcion,
       o.fecha_creacion,
       o.fecha_limite_oferta,
       t.nombre AS tipo,
       s.nombre AS subtipo
FROM OrdenCompra o
JOIN TipoOrden t     ON t.id_tipo     = o.id_tipo
LEFT JOIN SubtipoOrden s ON s.id_subtipo = o.id_subtipo
WHERE NOT EXISTS (SELECT 1 FROM Adjudicacion a WHERE a.id_orden = o.id_orden)
  AND o.fecha_creacion      <= CURRENT_DATE
  AND o.fecha_limite_oferta >= CURRENT_DATE;

/* =========================================================================
 * 6. REGLAS DE NEGOCIO (funciones y triggers)
 * ========================================================================= */

/* --- 6.1 Reglas de captura --- */

CREATE OR REPLACE FUNCTION fn_valida_fecha_orden()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.id_orden IS NOT NULL THEN
        IF (SELECT fecha_creacion FROM OrdenCompra WHERE id_orden = NEW.id_orden) < NEW.fecha_solicitud THEN
            RAISE EXCEPTION 'La fecha de creación de la orden no puede ser anterior a la fecha de solicitud del pedido.';
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_pedido_valida_fecha_orden
AFTER INSERT OR UPDATE ON Pedido
FOR EACH ROW EXECUTE FUNCTION fn_valida_fecha_orden();

CREATE OR REPLACE FUNCTION fn_valida_fecha_adjudicacion()
RETURNS TRIGGER AS $$
BEGIN
    IF (SELECT fecha_creacion FROM OrdenCompra WHERE id_orden = NEW.id_orden) > NEW.fecha_resolucion THEN
        RAISE EXCEPTION 'La fecha de adjudicación no puede ser anterior a la fecha de creación de la orden.';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_adjudicacion_valida_fecha
AFTER INSERT OR UPDATE ON Adjudicacion
FOR EACH ROW EXECUTE FUNCTION fn_valida_fecha_adjudicacion();

/* --- 6.2 Integridad de ofertas, detalle de adjudicación y órdenes --- */

CREATE OR REPLACE FUNCTION validar_oferta_integridad() RETURNS TRIGGER AS $$
BEGIN
   IF NOT EXISTS(SELECT 1 FROM Pedido p JOIN OrdenCompra o ON o.id_orden=p.id_orden JOIN ProveedorArticulo pa ON pa.id_articulo=p.id_articulo AND pa.id_proveedor=NEW.id_proveedor WHERE p.id_pedido=NEW.id_pedido AND NEW.fecha_oferta BETWEEN o.fecha_creacion AND o.fecha_limite_oferta) THEN
      RAISE EXCEPTION 'La oferta requiere pedido asignado, fecha dentro del plazo y artículo en catálogo';
   END IF;
   RETURN NEW;
END; $$ LANGUAGE plpgsql;

CREATE TRIGGER tr_Oferta_Integridad
BEFORE INSERT OR UPDATE ON Oferta
FOR EACH ROW EXECUTE FUNCTION validar_oferta_integridad();

CREATE OR REPLACE FUNCTION validar_detalle_integridad() RETURNS TRIGGER AS $$
BEGIN
   IF NOT EXISTS(SELECT 1 FROM Adjudicacion a JOIN Pedido p ON p.id_orden=a.id_orden JOIN Oferta f ON f.id_pedido=p.id_pedido WHERE a.id_adjudicacion=NEW.id_adjudicacion AND p.id_pedido=NEW.id_pedido AND f.id_oferta=NEW.id_oferta AND f.fecha_oferta<=a.fecha_resolucion AND NEW.cantidad_final<=p.cantidad) THEN
      RAISE EXCEPTION 'La oferta, pedido y adjudicación deben corresponder a la misma orden y cantidad solicitada';
   END IF;
   RETURN NEW;
END; $$ LANGUAGE plpgsql;

CREATE TRIGGER tr_DetalleAdjudicacion_Integridad
BEFORE INSERT OR UPDATE ON DetalleAdjudicacion
FOR EACH ROW EXECUTE FUNCTION validar_detalle_integridad();

CREATE OR REPLACE FUNCTION validar_orden_integridad() RETURNS TRIGGER AS $$
BEGIN
   IF EXISTS(SELECT 1 FROM Pedido p WHERE p.id_orden=NEW.id_orden AND p.fecha_solicitud>NEW.fecha_creacion) OR EXISTS(SELECT 1 FROM Adjudicacion a WHERE a.id_orden=NEW.id_orden AND a.fecha_resolucion<NEW.fecha_creacion) THEN
      RAISE EXCEPTION 'Las fechas de la orden contradicen sus solicitudes o adjudicación';
   END IF;
   IF NEW.id_subtipo IS NOT NULL AND NOT EXISTS(SELECT 1 FROM SubtipoOrden s WHERE s.id_subtipo=NEW.id_subtipo AND s.id_tipo=NEW.id_tipo) THEN
      RAISE EXCEPTION 'El subtipo no pertenece al tipo';
   END IF;
   RETURN NEW;
END; $$ LANGUAGE plpgsql;

CREATE TRIGGER tr_OrdenCompra_Integridad
BEFORE INSERT OR UPDATE ON OrdenCompra
FOR EACH ROW EXECUTE FUNCTION validar_orden_integridad();

/* --- 6.3 Historial: protege lo ya adjudicado o con ofertas --- */

CREATE OR REPLACE FUNCTION validar_pedido_historial() RETURNS TRIGGER AS $$
BEGIN
   IF (NEW.id_orden IS DISTINCT FROM OLD.id_orden OR NEW.id_articulo<>OLD.id_articulo) AND EXISTS(SELECT 1 FROM Oferta f WHERE f.id_pedido=NEW.id_pedido) THEN
      RAISE EXCEPTION 'No se puede reasignar ni cambiar el artículo de un pedido con ofertas';
   END IF;
   IF EXISTS(SELECT 1 FROM DetalleAdjudicacion d WHERE d.id_pedido=NEW.id_pedido AND d.cantidad_final>NEW.cantidad) THEN
      RAISE EXCEPTION 'La cantidad solicitada es menor que la adjudicada';
   END IF;
   RETURN NEW;
END; $$ LANGUAGE plpgsql;

CREATE TRIGGER tr_Pedido_Historial
BEFORE UPDATE ON Pedido
FOR EACH ROW EXECUTE FUNCTION validar_pedido_historial();

CREATE OR REPLACE FUNCTION validar_adjudicacion_historial() RETURNS TRIGGER AS $$
BEGIN
   IF EXISTS(SELECT 1 FROM DetalleAdjudicacion d JOIN Pedido p ON p.id_pedido=d.id_pedido JOIN Oferta f ON f.id_oferta=d.id_oferta WHERE d.id_adjudicacion=NEW.id_adjudicacion AND (p.id_orden<>NEW.id_orden OR f.fecha_oferta>NEW.fecha_resolucion)) THEN
      RAISE EXCEPTION 'La resolución contradice pedidos u ofertas adjudicados';
   END IF;
   RETURN NEW;
END; $$ LANGUAGE plpgsql;

CREATE TRIGGER tr_Adjudicacion_Historial
BEFORE UPDATE ON Adjudicacion
FOR EACH ROW EXECUTE FUNCTION validar_adjudicacion_historial();

CREATE OR REPLACE FUNCTION validar_oferta_historial() RETURNS TRIGGER AS $$
BEGIN
   IF (NEW.id_proveedor<>OLD.id_proveedor OR NEW.id_pedido<>OLD.id_pedido OR NEW.precio_unitario<>OLD.precio_unitario OR NEW.fecha_oferta<>OLD.fecha_oferta) AND EXISTS(SELECT 1 FROM DetalleAdjudicacion d WHERE d.id_oferta=NEW.id_oferta) THEN
      RAISE EXCEPTION 'La oferta adjudicada no puede modificarse';
   END IF;
   RETURN NEW;
END; $$ LANGUAGE plpgsql;

CREATE TRIGGER tr_Oferta_Historial
BEFORE UPDATE ON Oferta
FOR EACH ROW EXECUTE FUNCTION validar_oferta_historial();

CREATE OR REPLACE FUNCTION validar_orden_ofertas() RETURNS TRIGGER AS $$
BEGIN
   IF EXISTS(SELECT 1 FROM Pedido p JOIN Oferta f ON f.id_pedido=p.id_pedido WHERE p.id_orden=NEW.id_orden AND (f.fecha_oferta<NEW.fecha_creacion OR f.fecha_oferta>NEW.fecha_limite_oferta)) THEN
      RAISE EXCEPTION 'Las nuevas fechas dejan ofertas fuera del plazo';
   END IF;
   RETURN NEW;
END; $$ LANGUAGE plpgsql;

CREATE TRIGGER tr_OrdenCompra_Ofertas
BEFORE UPDATE ON OrdenCompra
FOR EACH ROW EXECUTE FUNCTION validar_orden_ofertas();

CREATE OR REPLACE FUNCTION validar_catalogo_historial() RETURNS TRIGGER AS $$
BEGIN
   IF EXISTS(SELECT 1 FROM Oferta f JOIN Pedido p ON p.id_pedido=f.id_pedido WHERE f.id_proveedor=OLD.id_proveedor AND p.id_articulo=OLD.id_articulo) THEN
      RAISE EXCEPTION 'No puede eliminar catálogo con ofertas históricas';
   END IF;
   RETURN OLD;
END; $$ LANGUAGE plpgsql;

CREATE TRIGGER tr_ProveedorArticulo_Historial
BEFORE DELETE ON ProveedorArticulo
FOR EACH ROW EXECUTE FUNCTION validar_catalogo_historial();
